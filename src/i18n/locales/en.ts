/**
 * English dictionary. Values are the exact strings the terminal rendered before
 * localization, so an English session stays byte-identical; the key set is
 * checked complete against the Chinese source of truth in `zh.ts` — a missing
 * or extra key here is a compile error.
 *
 * An entry is a function where English needs a plural form, which Chinese does
 * not carry (`count.*`, `diff.files`, `mcp.toolCount`).
 * @module @deepseek-ai/dsh-tui/i18n/locales/en
 */

